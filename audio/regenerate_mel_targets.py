"""
Neural + audio data preparation for the mikko auditory decoding pipeline,
following the preprocessing methodology described in:

    Heelan, Lee, et al. "Decoding speech from spike-based neural population
    recordings in secondary auditory cortex of non-human primates."
    Communications Biology 2, 466 (2019).

Key differences from the original trial-isolation-based loader:
  - No trial carving. Each recording session is treated as one continuous,
    sequentially-binned time series (per the paper's methods), later
    sequentially concatenated across sessions and sequentially split into
    train/valid/test (80/10/10) downstream by the existing Docker pipeline.
  - Spike detection uses the paper's actual method: 2nd-order elliptic
    bandpass -> per-channel noise threshold via median absolute deviation
    (Quiroga et al. 2004) -> negative threshold crossings -> binned counts,
    not z-score thresholding, ZCA whitening, or CAR (none of which the
    paper describes).
  - The mel-spectrogram target is generated by calling the already-verified
    `mikko_test` Docker container (librosa_mel_transformer, mel_transform
    method) rather than reimplementing it here, so there is exactly one
    source of truth for that computation.
  - `ainp8` (the word-presence mask) is used only for QC: shading word
    epochs on plots and clipping one representative WAV for a listen-back
    sanity check. It does NOT cut the data into separate trials.

Prerequisites (host machine, not inside any container):
    pip install neo scipy matplotlib librosa

Usage:
    python3 prepare_auditory_data.py
"""

import json
import subprocess
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from neo.io import BlackrockIO
from scipy.io import wavfile
from scipy.signal import ellip, filtfilt

# ---------------------------------------------------------------------------
# CONFIG — tune these. Defaults are placeholders, not the paper's optimum.
# ---------------------------------------------------------------------------

# Where your raw .ns5 files live, and where outputs go.
BASE_DIR = Path("/Users/benjaminfalkenburg/Dropbox/SNN_Main/data/Auditory_cortex/Neil/Complex/aSTG")
OUT_DIR = Path("datasets_v2")

# Neural preprocessing (paper grid-searched these — see Table 1 / Fig 4)
BANDPASS_LOW_HZ = 600.0
BANDPASS_HIGH_HZ = 2500.0
ELLIPTIC_ORDER = 2
ELLIPTIC_RIPPLE_DB = 0.5     # passband ripple; not specified by the paper
ELLIPTIC_ATTEN_DB = 40.0     # stopband attenuation; not specified by the paper
THRESHOLD_FACTOR = 4.0       # paper grid-searched {2, 3, 4, 5}

# Bin size MUST match the mel-spectrogram hop size below — this is what
# aligns a neural feature bin with an audio target bin one-to-one.
BIN_MS = 40.0

# Mel-spectrogram target (paper's finalized choices, from "Audio preprocessing")
NUM_MELS = 128
FFT_SIZE = 2048
MEL_PARAMS = dict(
    ref_level_db=20,
    power=1.5,
    griffin_lim_iters=60,
    preemphasis=0.97,
    max_abs_value=4,
    min_level_db=-100,
    random_seed=1337,
)

# Fraction of each session used to fit the per-channel noise threshold —
# mirrors TRAIN_DECIMAL used everywhere else in the pipeline, to avoid
# leaking validation/test data into the threshold estimate.
TRAIN_FRACTION_FOR_THRESHOLD = 0.8

# ainp8: values roughly 0-5000; LOW state = word being spoken.
AINP8_SPEECH_THRESHOLD = 2500.0

MIKKO_IMAGE = "mikko_test"


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------
def load_session(path):
    """Load one .ns5 file. Returns audio (1D), ainp8 (1D), spikes (N x C
    raw broadband neural data), and sampling rate fs."""
    print(f"  Loading raw neural data: {path}")
    reader = BlackrockIO(filename=str(path))
    blk = reader.read_block()

    audio_sig = None
    for asig in blk.segments[0].analogsignals:
        if asig.shape[1] < 90:
            audio_sig = asig
            break
    if audio_sig is None:
        raise ValueError(f"Could not find the audio/ainp8 analog signal group in {path}")

    fs = float(audio_sig.sampling_rate.rescale("Hz").magnitude)

    audio = np.asarray(audio_sig[:, 0]).flatten().astype(np.float64)
    ainp8 = np.asarray(audio_sig[:, 1]).flatten().astype(np.float64)

    spikes_sig = blk.segments[0].analogsignals[0]
    # Rescale to microvolts explicitly, per the paper ("scaled to units of
    # microvolts"). If your recording is already in a physical unit, this
    # is a no-op beyond a unit conversion factor.
    try:
        spikes_sig = spikes_sig.rescale("uV")
    except Exception as e:
        print(f"  WARNING: could not rescale neural signal to uV ({e}); "
              f"proceeding with raw units — verify manually.")
    spikes = np.asarray(spikes_sig).astype(np.float64)  # shape (N, num_channels)

    return audio, ainp8, spikes, fs


# ---------------------------------------------------------------------------
# Neural preprocessing — matches the paper's methods section
# ---------------------------------------------------------------------------
def bandpass_elliptic(data, fs, low=BANDPASS_LOW_HZ, high=BANDPASS_HIGH_HZ,
                       order=ELLIPTIC_ORDER, ripple=ELLIPTIC_RIPPLE_DB,
                       atten=ELLIPTIC_ATTEN_DB):
    """2nd-order bandpass elliptic filter, as specified in the paper
    (Neural preprocessing). Applied per-channel (axis=0 is time)."""
    nyq = fs / 2
    b, a = ellip(order, ripple, atten, [low / nyq, high / nyq], btype="band")
    return filtfilt(b, a, data, axis=0)


def compute_negative_thresholds(filtered, train_fraction=TRAIN_FRACTION_FOR_THRESHOLD,
                                 threshold_factor=THRESHOLD_FACTOR):
    """Per-channel noise level via median absolute deviation (Quiroga et al.
    2004: noise = median(|x|) / 0.6745), estimated only on the training
    fraction of the session, then scaled by threshold_factor. Returns a
    negative threshold per channel."""
    n_train = int(filtered.shape[0] * train_fraction)
    train_segment = filtered[:n_train]
    noise = np.median(np.abs(train_segment), axis=0) / 0.6745
    thresholds = -threshold_factor * noise
    return thresholds  # shape (num_channels,)


def detect_negative_crossings(channel, threshold):
    """Sample indices where `channel` crosses from >= threshold to
    < threshold (a negative-going threshold crossing)."""
    below = channel < threshold
    crossing_idx = np.where(np.diff(below.astype(np.int8)) == 1)[0] + 1
    return crossing_idx


def bin_spike_counts(filtered, fs, thresholds, bin_ms=BIN_MS):
    """Detect negative threshold crossings per channel and bin them into
    non-overlapping windows of bin_ms. Returns (n_bins, num_channels)."""
    n_samples, n_channels = filtered.shape
    bin_samples = int(round(bin_ms / 1000.0 * fs))
    n_bins = n_samples // bin_samples
    edges = np.arange(0, (n_bins + 1) * bin_samples, bin_samples)

    counts = np.zeros((n_bins, n_channels), dtype=np.float32)
    all_crossings = []  # kept for the raster QC plot
    for ch in range(n_channels):
        crossings = detect_negative_crossings(filtered[:, ch], thresholds[ch])
        all_crossings.append(crossings)
        hist, _ = np.histogram(crossings, bins=edges)
        counts[:, ch] = hist

    return counts, all_crossings


# ---------------------------------------------------------------------------
# ainp8 — QC only, never used to build features/targets
# ---------------------------------------------------------------------------
def extract_speech_epochs(ainp8, threshold=AINP8_SPEECH_THRESHOLD):
    """Contiguous (start_idx, end_idx) sample ranges where ainp8 is LOW
    (a word is being spoken)."""
    is_speech = ainp8 < threshold
    diff = np.diff(is_speech.astype(np.int8))
    onsets = np.where(diff == 1)[0] + 1
    offsets = np.where(diff == -1)[0] + 1
    if is_speech[0]:
        onsets = np.concatenate([[0], onsets])
    if is_speech[-1]:
        offsets = np.concatenate([offsets, [len(is_speech)]])
    return list(zip(onsets, offsets))


def save_qc_wav(audio, fs, epoch, out_path, pad_s=0.2):
    """Save one representative word epoch (plus a little padding) as a WAV,
    purely to listen back and confirm ainp8 alignment with actual speech."""
    start, end = epoch
    pad = int(pad_s * fs)
    start = max(0, start - pad)
    end = min(len(audio), end + pad)
    clip = audio[start:end].astype(np.float64)
    peak = np.max(np.abs(clip))
    if peak > 0:
        clip = clip / peak
    clip_i16 = (clip * 32767).astype(np.int16)
    wavfile.write(out_path, int(fs), clip_i16)
    print(f"  Saved QC wav: {out_path}")


# ---------------------------------------------------------------------------
# Visualization
# ---------------------------------------------------------------------------
def plot_ainp8_qc(audio, ainp8, epochs, fs, out_path, window_s=10.0):
    """Raw audio + ainp8 trace with detected speech epochs shaded, for the
    first `window_s` seconds — confirms ainp8 thresholding lines up with
    actual audio energy."""
    n = int(window_s * fs)
    t = np.arange(n) / fs

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(12, 6), sharex=True)
    ax1.plot(t, audio[:n], linewidth=0.5)
    ax1.set_ylabel("Audio (raw)")
    ax1.set_title("Audio waveform with detected speech epochs (shaded)")

    ax2.plot(t, ainp8[:n], linewidth=0.5, color="darkorange")
    ax2.axhline(AINP8_SPEECH_THRESHOLD, color="gray", linestyle="--", linewidth=0.8)
    ax2.set_ylabel("ainp8")
    ax2.set_xlabel("Time (s)")
    ax2.set_title("ainp8 mask (dashed line = speech threshold)")

    for start, end in epochs:
        if start / fs > window_s:
            break
        s, e = start / fs, min(end / fs, window_s)
        ax1.axvspan(s, e, color="green", alpha=0.15)
        ax2.axvspan(s, e, color="green", alpha=0.15)

    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close(fig)
    print(f"  Saved: {out_path}")


def plot_spike_raster(all_crossings, fs, out_path, window_s=10.0, n_channels_to_show=96):
    """Raster of detected spike crossing times across channels, for the
    first `window_s` seconds — a QC check that thresholding is picking up
    plausible spiking activity, not just noise or nothing."""
    fig, ax = plt.subplots(figsize=(12, 6))
    for ch in range(min(n_channels_to_show, len(all_crossings))):
        times = all_crossings[ch] / fs
        times = times[times < window_s]
        ax.scatter(times, np.full_like(times, ch), s=1, color="black")
    ax.set_xlabel("Time (s)")
    ax.set_ylabel("Channel")
    ax.set_title(f"Spike raster (first {window_s:.0f}s)")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close(fig)
    print(f"  Saved: {out_path}")


def plot_binned_features(features, bin_ms, out_path, window_s=10.0):
    """Heatmap of binned spike counts (channels x time), first window_s
    seconds — the actual feature array the decoders will see."""
    n_bins_to_show = int(window_s * 1000 / bin_ms)
    n_bins_to_show = min(n_bins_to_show, features.shape[0])
    t = np.arange(n_bins_to_show) * bin_ms / 1000.0

    fig, ax = plt.subplots(figsize=(12, 5))
    im = ax.pcolormesh(t, np.arange(features.shape[1]),
                        features[:n_bins_to_show].T, cmap="viridis", shading="auto")
    ax.set_xlabel("Time (s)")
    ax.set_ylabel("Channel")
    ax.set_title("Binned spike counts (this is features.npy)")
    fig.colorbar(im, ax=ax, label="Spike count / bin")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close(fig)
    print(f"  Saved: {out_path}")


def plot_mel_preview(audio, fs, out_path, window_s=10.0):
    """Quick mel-spectrogram preview using librosa directly, purely for a
    fast visual sanity check. NOT the same code path as the real target —
    the actual targets.npy comes from the mikko_test container below, which
    additionally applies preemphasis and dB-normalization. If this preview
    looks structurally sane (formant bands visible during speech, quiet
    during silence), that's a reasonable signal but not a substitute for
    inspecting the real targets.npy."""
    import librosa

    n = int(window_s * fs)
    clip = audio[:n]
    S = librosa.feature.melspectrogram(
        y=clip.astype(np.float32), sr=int(fs), n_fft=FFT_SIZE,
        hop_length=int(BIN_MS / 1000 * fs), n_mels=NUM_MELS,
    )
    S_db = librosa.power_to_db(S, ref=np.max)

    fig, ax = plt.subplots(figsize=(12, 5))
    im = ax.imshow(S_db, aspect="auto", origin="lower", cmap="magma")
    ax.set_xlabel("Frame")
    ax.set_ylabel("Mel band")
    ax.set_title("Mel-spectrogram PREVIEW (quick look only — not the real target)")
    fig.colorbar(im, ax=ax, label="dB")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close(fig)
    print(f"  Saved: {out_path}")


# ---------------------------------------------------------------------------
# Real mel-spectrogram target — via the verified mikko_test container
# ---------------------------------------------------------------------------
def generate_mel_targets_via_docker(audio, fs, data_dir, session_tag):
    """Writes audio as a .npy, then calls the already-verified mikko_test
    container (mel_transform method) to produce the real mel-spectrogram
    target array — single source of truth, matching what every decoder in
    the pipeline was validated against."""
    audio_npy = data_dir / f"{session_tag}_audio_raw.npy"
    mel_npy = data_dir / f"{session_tag}_mel_target.npy"
    config_path = data_dir / f"{session_tag}_mel_config.json"

    # Normalize to roughly [-1, 1] before dB conversion. Raw neural-rig
    # audio channels are typically stored in raw ADC units (often in the
    # thousands), not the ~[-1,1] float range dB-based pipelines assume.
    # Skipping this causes near-total clipping at the mel normalization
    # ceiling (+max_abs_value) throughout almost the entire recording.
    peak = np.max(np.abs(audio))
    audio_normalized = audio / (peak + 1e-8)
    np.save(audio_npy, audio_normalized.reshape(-1, 1).astype(np.float32))

    config = {
        "params": {
            "method": "mel_transform",
            "sampling_rate": fs,
            "fft_size": FFT_SIZE,
            "num_mels": NUM_MELS,
            "frame_shift_ms": BIN_MS,
            "save_transformer": False,
            **MEL_PARAMS,
        },
        "input_pathnames": {"input": str(audio_npy)},
        "output_pathnames": {"mel_npy": str(mel_npy)},
    }
    with open(config_path, "w") as f:
        json.dump(config, f, indent=2)

    print(f"  Running {MIKKO_IMAGE} for mel-spectrogram target ({session_tag})...")
    result = subprocess.run(
        ["docker", "run", "--rm", "-v", f"{data_dir}:{data_dir}", MIKKO_IMAGE, str(config_path)]
    )
    if result.returncode != 0:
        raise RuntimeError(f"mikko_test failed for {session_tag} (exit {result.returncode})")

    return np.load(mel_npy)


# ---------------------------------------------------------------------------
# Per-session pipeline
# ---------------------------------------------------------------------------
def process_session(path, data_dir, session_tag):
    audio, ainp8, spikes, fs = load_session(path)

    print("  Bandpass filtering (elliptic)...")
    filtered = bandpass_elliptic(spikes, fs)

    print("  Computing per-channel noise thresholds (MAD, train fraction only)...")
    thresholds = compute_negative_thresholds(filtered)

    print("  Detecting negative threshold crossings and binning...")
    features, all_crossings = bin_spike_counts(filtered, fs, thresholds)

    print("  Generating mel-spectrogram target via mikko_test...")
    targets = generate_mel_targets_via_docker(audio, fs, data_dir, session_tag)

    # Bin-count alignment check — spike binning (fixed-width non-overlapping
    # windows) and librosa's STFT framing (centered, hop-based) don't
    # guarantee an identical frame count. Truncate to the shorter of the two
    # rather than assuming they match.
    n = min(features.shape[0], targets.shape[0])
    if abs(features.shape[0] - targets.shape[0]) > 2:
        print(f"  WARNING: features ({features.shape[0]} bins) and targets "
              f"({targets.shape[0]} bins) differ by more than 2 bins — "
              f"check BIN_MS / hop alignment before trusting this session.")
    features, targets = features[:n], targets[:n]

    # QC outputs
    qc_dir = data_dir / "qc" / session_tag
    qc_dir.mkdir(parents=True, exist_ok=True)

    epochs = extract_speech_epochs(ainp8)
    print(f"  Detected {len(epochs)} speech epochs from ainp8")
    if epochs:
        save_qc_wav(audio, fs, epochs[0], qc_dir / "sample_word.wav")

    plot_ainp8_qc(audio, ainp8, epochs, fs, qc_dir / "ainp8_qc.png")
    plot_spike_raster(all_crossings, fs, qc_dir / "spike_raster.png")
    plot_binned_features(features, BIN_MS, qc_dir / "binned_features.png")
    try:
        plot_mel_preview(audio, fs, qc_dir / "mel_preview.png")
    except ImportError:
        print("  (skipping mel preview plot — librosa not installed on host)")

    return features, targets


# ---------------------------------------------------------------------------
# Main — walk sessions, process, sequentially concatenate
# ---------------------------------------------------------------------------
def main():
    out_dir = OUT_DIR.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    skips = {".DS_Store", "desktop.ini"}
    days = sorted(d for d in BASE_DIR.iterdir() if d.name not in skips)

    all_features, all_targets = [], []

    for day in days:
        sessions = sorted(day.glob("*.ns5"))
        for session_path in sessions:
            session_tag = f"{day.name}_{session_path.stem}"
            print(f"\nProcessing {session_tag}...")
            try:
                features, targets = process_session(session_path, out_dir, session_tag)
                all_features.append(features)
                all_targets.append(targets)
            except Exception as e:
                print(f"  FAILED on {session_tag}: {e}")

    if not all_features:
        print("No sessions processed successfully — nothing to concatenate.")
        return

    features_full = np.concatenate(all_features, axis=0)
    targets_full = np.concatenate(all_targets, axis=0)

    np.save(out_dir / "features.npy", features_full)
    np.save(out_dir / "targets.npy", targets_full)

    print(f"\nFinal features.npy: {features_full.shape}")
    print(f"Final targets.npy:  {targets_full.shape}")
    print(f"Saved to {out_dir}/features.npy and {out_dir}/targets.npy")
    print(f"QC plots and sample wav files are under {out_dir}/qc/<session>/")


if __name__ == "__main__":
    main()