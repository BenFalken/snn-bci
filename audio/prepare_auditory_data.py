"""
prepare_auditory_data.py

Neural + audio data preparation for the mikko auditory decoding pipeline,
following the preprocessing methodology described in Heelan, Lee, et al.
"Decoding speech from spike-based neural population recordings in
secondary auditory cortex of non-human primates", Communications Biology
2, 466 (2019).

Processes exactly ONE (subject, region, date) at a time -- sessions are
concatenated across .ns5 files WITHIN that date, never across dates,
per empirical findings that cross-date concatenation degrades decoding
(different days appear to have different recording characteristics).

Neural preprocessing: 2nd-order elliptic bandpass -> per-channel noise
threshold via median absolute deviation (Quiroga et al. 2004) -> negative
threshold crossings -> binned counts, matching the paper's stated method.

The mel-spectrogram target is generated by calling the verified mikko_test
Docker container (librosa_mel_transformer, mel_transform method) -- single
source of truth for that computation, not reimplemented here.

`ainp8` (the word-presence mask) is used for two things, both QC/inspection
only -- it never determines what goes into features.npy/targets.npy:
  1. Selecting candidate "trials" (speech epochs) to visualize.
  2. Producing unified, x-axis-aligned figures (raster + binned features +
     mel-spectrogram) per candidate trial, so you can visually compare
     several real word events and confirm the pipeline is behaving
     sensibly before committing to a full decoder run.

Prerequisites (host machine, not inside any container):
    pip install neo scipy matplotlib librosa

Usage:
    python3 prepare_auditory_data.py \
        --subject Neil --region aSTG --date 07_19_11 \
        --raw-base-dir "/Users/you/Dropbox/SNN_Main/data/Auditory_cortex/Neil/Complex/aSTG"
"""

import argparse
import json
import subprocess
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from neo.io import BlackrockIO
from scipy.io import wavfile
from scipy.signal import ellip, filtfilt

from pipeline_paths import PipelinePaths, add_identity_args

# ---------------------------------------------------------------------------
# CONFIG -- tune these. Defaults are placeholders, not the paper's optimum,
# except where noted as matching the paper's finalized choices.
# ---------------------------------------------------------------------------

# Neural preprocessing (paper grid-searched these -- see Table 1 / Fig 4)
BANDPASS_LOW_HZ = 600.0
BANDPASS_HIGH_HZ = 2500.0
ELLIPTIC_ORDER = 2
ELLIPTIC_RIPPLE_DB = 0.5     # passband ripple; not specified by the paper
ELLIPTIC_ATTEN_DB = 40.0     # stopband attenuation; not specified by the paper
THRESHOLD_FACTOR = 4.0       # paper grid-searched {2, 3, 4, 5}

# Bin size MUST match the mel-spectrogram hop size below -- this is what
# aligns a neural feature bin with an audio target bin one-to-one.
BIN_MS = 40.0

# Mel-spectrogram target (paper's finalized choices, from "Audio preprocessing")
NUM_MELS = 128
FFT_SIZE = 2048
MEL_PARAMS = dict(
    ref_level_db=20,
    power=1.5,
    griffin_lim_iters=60,
    preemphasis=0.97,
    max_abs_value=4,
    min_level_db=-100,
    random_seed=1337,
)

# Fraction of each session used to fit the per-channel noise threshold --
# mirrors TRAIN_DECIMAL used everywhere else in the pipeline, to avoid
# leaking validation/test data into the threshold estimate.
TRAIN_FRACTION_FOR_THRESHOLD = 0.8

# ainp8: values roughly 0-5000; LOW state = word being spoken.
AINP8_SPEECH_THRESHOLD = 2500.0

MIKKO_IMAGE = "mikko_test"


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------
def load_session(path):
    """Load one .ns5 file. Returns audio (1D), ainp8 (1D), spikes (N x C
    raw broadband neural data), and sampling rate fs."""
    print(f"  Loading raw neural data: {path}")
    reader = BlackrockIO(filename=str(path))
    blk = reader.read_block()

    audio_sig = None
    for asig in blk.segments[0].analogsignals:
        if asig.shape[1] < 90:
            audio_sig = asig
            break
    if audio_sig is None:
        raise ValueError(f"Could not find the audio/ainp8 analog signal group in {path}")

    fs = float(audio_sig.sampling_rate.rescale("Hz").magnitude)

    audio = np.asarray(audio_sig[:, 0]).flatten().astype(np.float64)
    ainp8 = np.asarray(audio_sig[:, 1]).flatten().astype(np.float64)

    spikes_sig = blk.segments[0].analogsignals[0]
    try:
        spikes_sig = spikes_sig.rescale("uV")
    except Exception as e:
        print(f"  WARNING: could not rescale neural signal to uV ({e}); "
              f"proceeding with raw units -- verify manually.")
    spikes = np.asarray(spikes_sig)  # shape (N, num_channels); each channel goes to float64 when it is filtered

    return audio, ainp8, spikes, fs


# ---------------------------------------------------------------------------
# Neural preprocessing -- matches the paper's methods section
# ---------------------------------------------------------------------------
def bandpass_elliptic(data, fs, low=BANDPASS_LOW_HZ, high=BANDPASS_HIGH_HZ,
                       order=ELLIPTIC_ORDER, ripple=ELLIPTIC_RIPPLE_DB,
                       atten=ELLIPTIC_ATTEN_DB):
    """2nd-order bandpass elliptic filter, as specified in the paper
    (Neural preprocessing). Applied per-channel (axis=0 is time)."""
    nyq = fs / 2
    b, a = ellip(order, ripple, atten, [low / nyq, high / nyq], btype="band")
    return filtfilt(b, a, data, axis=0)


def compute_negative_thresholds(filtered, train_fraction=TRAIN_FRACTION_FOR_THRESHOLD,
                                 threshold_factor=THRESHOLD_FACTOR):
    """Per-channel noise level via median absolute deviation (Quiroga et al.
    2004: noise = median(|x|) / 0.6745), estimated only on the training
    fraction of the session, then scaled by threshold_factor. Returns a
    negative threshold per channel."""
    n_train = int(filtered.shape[0] * train_fraction)
    train_segment = filtered[:n_train]
    noise = np.median(np.abs(train_segment), axis=0) / 0.6745
    return -threshold_factor * noise  # shape (num_channels,)


def detect_negative_crossings(channel, threshold):
    """Sample indices where `channel` crosses from >= threshold to
    < threshold (a negative-going threshold crossing)."""
    below = channel < threshold
    return np.where(np.diff(below.astype(np.int8)) == 1)[0] + 1


def bin_spike_counts(filtered, fs, thresholds, bin_ms=BIN_MS):
    """Detect negative threshold crossings per channel and bin them into
    non-overlapping windows of bin_ms. Returns (n_bins, num_channels) plus
    the raw per-channel crossing sample-indices (kept for raster plotting)."""
    n_samples, n_channels = filtered.shape
    bin_samples = int(round(bin_ms / 1000.0 * fs))
    n_bins = n_samples // bin_samples
    edges = np.arange(0, (n_bins + 1) * bin_samples, bin_samples)

    counts = np.zeros((n_bins, n_channels), dtype=np.float32)
    all_crossings = []
    for ch in range(n_channels):
        crossings = detect_negative_crossings(filtered[:, ch], thresholds[ch])
        all_crossings.append(crossings)
        hist, _ = np.histogram(crossings, bins=edges)
        counts[:, ch] = hist

    return counts, all_crossings


# ---------------------------------------------------------------------------
# ainp8 -- QC/trial-selection only, never used to build features/targets
# ---------------------------------------------------------------------------
def extract_speech_epochs(ainp8, threshold=AINP8_SPEECH_THRESHOLD):
    """Contiguous (start_idx, end_idx) sample ranges where ainp8 is LOW
    (a word is being spoken)."""
    is_speech = ainp8 < threshold
    diff = np.diff(is_speech.astype(np.int8))
    onsets = np.where(diff == 1)[0] + 1
    offsets = np.where(diff == -1)[0] + 1
    if is_speech[0]:
        onsets = np.concatenate([[0], onsets])
    if is_speech[-1]:
        offsets = np.concatenate([offsets, [len(is_speech)]])
    return list(zip(onsets, offsets))


def save_trial_wav(audio, fs, epoch, out_path, pad_s=0.3):
    """Save one word epoch (plus padding) as a WAV for a listen-back check."""
    start, end = epoch
    pad = int(pad_s * fs)
    start, end = max(0, start - pad), min(len(audio), end + pad)
    clip = audio[start:end].astype(np.float64)
    peak = np.max(np.abs(clip))
    if peak > 0:
        clip = clip / peak
    wavfile.write(out_path, int(fs), (clip * 32767).astype(np.int16))


# ---------------------------------------------------------------------------
# Unified, x-axis-aligned per-trial QC figure
#
# Why the gridspec dance: imshow/pcolormesh's fig.colorbar() call
# automatically SHRINKS its parent axes to make room for the colorbar. A
# bare scatter axes has no colorbar, so it never shrinks -- even with
# sharex=True, the resulting plot AREAS end up different widths, so the
# x-axes visually don't line up despite sharing the same data coordinates.
# Fix: explicitly reserve a narrow colorbar column via gridspec for every
# row, including the raster row (whose "colorbar" axis is just switched
# off) -- every row's main plot area is then guaranteed identical width.
# ---------------------------------------------------------------------------
def plot_unified_trial_qc(all_crossings, features, targets, fs, bin_ms,
                           epoch, trial_idx, out_path, pad_s=0.3):
    start_sample, end_sample = epoch
    pad = int(pad_s * fs)
    start_sample = max(0, start_sample - pad)
    end_sample = end_sample + pad
    t_start, t_end = start_sample / fs, end_sample / fs

    bin_samples = int(round(bin_ms / 1000.0 * fs))
    bin_start = max(0, start_sample // bin_samples)
    bin_end = min(features.shape[0], -(-end_sample // bin_samples))  # ceil div
    bin_times = (np.arange(bin_start, bin_end) + 0.5) * bin_ms / 1000.0

    fig = plt.figure(figsize=(12, 10))
    gs = fig.add_gridspec(3, 2, width_ratios=[30, 1], hspace=0.4, wspace=0.05)

    # --- Row 1: raster (real spike-crossing times, not binned) -----------
    ax_raster = fig.add_subplot(gs[0, 0])
    ax_raster_spacer = fig.add_subplot(gs[0, 1])
    ax_raster_spacer.axis("off")  # reserves identical width to a real colorbar

    for ch, crossings in enumerate(all_crossings):
        times = crossings / fs
        mask = (times >= t_start) & (times <= t_end)
        ax_raster.scatter(times[mask], np.full(mask.sum(), ch), s=3, color="black")
    ax_raster.set_ylabel("Channel")
    ax_raster.set_title(f"Trial {trial_idx}: spike raster "
                         f"({t_end - t_start:.2f}s window)")

    # --- Row 2: binned spike counts (features.npy, this trial's slice) ---
    ax_feat = fig.add_subplot(gs[1, 0], sharex=ax_raster)
    ax_feat_cbar = fig.add_subplot(gs[1, 1])
    im_feat = ax_feat.pcolormesh(
        bin_times, np.arange(features.shape[1]), features[bin_start:bin_end].T,
        cmap="viridis", shading="auto",
    )
    fig.colorbar(im_feat, cax=ax_feat_cbar, label="Spike count / bin")
    ax_feat.set_ylabel("Channel")
    ax_feat.set_title("Binned spike counts (features.npy)")

    # --- Row 3: real mel-spectrogram (targets.npy, this trial's slice) ---
    ax_mel = fig.add_subplot(gs[2, 0], sharex=ax_raster)
    ax_mel_cbar = fig.add_subplot(gs[2, 1])
    im_mel = ax_mel.pcolormesh(
        bin_times, np.arange(targets.shape[1]), targets[bin_start:bin_end].T,
        cmap="magma", shading="auto",
    )
    fig.colorbar(im_mel, cax=ax_mel_cbar, label="Normalized mel dB")
    ax_mel.set_ylabel("Mel band")
    ax_mel.set_xlabel("Time (s)")
    ax_mel.set_title("Mel-spectrogram (targets.npy)")

    for ax in (ax_raster, ax_feat, ax_mel):
        ax.set_xlim(t_start, t_end)

    plt.savefig(out_path, dpi=200)
    plt.close(fig)


# ---------------------------------------------------------------------------
# Real mel-spectrogram target -- via the verified mikko_test container
# ---------------------------------------------------------------------------
def generate_mel_targets_via_docker(audio, fs, prep_dir, session_tag):
    """Writes audio as a .npy, then calls the verified mikko_test container
    (mel_transform method) to produce the real mel-spectrogram target array
    -- single source of truth, matching what every decoder was validated
    against."""
    audio_npy = prep_dir / f"{session_tag}_audio_raw.npy"
    mel_npy = prep_dir / f"{session_tag}_mel_target.npy"
    config_path = prep_dir / f"{session_tag}_mel_config.json"

    peak = np.max(np.abs(audio))
    audio_normalized = (audio / (peak + 1e-8)).reshape(-1, 1).astype(np.float32)
    np.save(audio_npy, audio_normalized)

    config = {
        "params": {
            "method": "mel_transform",
            "sampling_rate": fs,
            "fft_size": FFT_SIZE,
            "num_mels": NUM_MELS,
            "frame_shift_ms": BIN_MS,
            "save_transformer": False,
            **MEL_PARAMS,
        },
        "input_pathnames": {"input": str(audio_npy)},
        "output_pathnames": {"mel_npy": str(mel_npy)},
    }
    with open(config_path, "w") as f:
        json.dump(config, f, indent=2)

    print(f"  Running {MIKKO_IMAGE} for mel-spectrogram target ({session_tag})...")
    result = subprocess.run(
        ["docker", "run", "--rm", "-v", f"{prep_dir}:{prep_dir}", MIKKO_IMAGE, str(config_path)]
    )
    if result.returncode != 0:
        raise RuntimeError(f"mikko_test failed for {session_tag} (exit {result.returncode})")

    return np.load(mel_npy)


# ---------------------------------------------------------------------------
# Per-session pipeline
# ---------------------------------------------------------------------------
def process_session(path, paths, session_tag, n_qc_trials=5):
    audio, ainp8, spikes, fs = load_session(path)

    # one channel at a time (the same float64 filter, threshold and crossings as on the whole matrix, so the same
    # result), so that memory stays at the raw recording plus one channel instead of several full-size copies
    print("  Bandpass filtering (elliptic), thresholds (MAD, train fraction) and crossings, channel by channel...")
    n_ch = spikes.shape[1]
    cols, thr, all_crossings = [], np.zeros(n_ch), []
    for ch in range(n_ch):
        f = bandpass_elliptic(spikes[:, ch].astype(np.float64), fs)
        thr[ch] = compute_negative_thresholds(f[:, None])[0]
        c, x = bin_spike_counts(f[:, None], fs, thr[ch:ch + 1])
        cols.append(c[:, 0])
        all_crossings.append(x[0])
    features = np.stack(cols, 1).astype(np.float32)
    thresholds = thr

    print("  Generating mel-spectrogram target via mikko_test...")
    targets = generate_mel_targets_via_docker(audio, fs, paths.prep, session_tag)

    n = min(features.shape[0], targets.shape[0])
    if abs(features.shape[0] - targets.shape[0]) > 2:
        print(f"  WARNING: features ({features.shape[0]} bins) and targets "
              f"({targets.shape[0]} bins) differ by more than 2 bins -- "
              f"check BIN_MS / hop alignment before trusting this session.")
    features, targets = features[:n], targets[:n]

    session_qc_dir = paths.qc / session_tag
    session_qc_dir.mkdir(parents=True, exist_ok=True)

    epochs = extract_speech_epochs(ainp8)
    print(f"  Detected {len(epochs)} speech epochs from ainp8")
    epochs_by_duration = sorted(epochs, key=lambda e: e[1] - e[0], reverse=True)

    for i, epoch in enumerate(epochs_by_duration[:n_qc_trials]):
        duration_s = (epoch[1] - epoch[0]) / fs
        tag = f"trial_{i:02d}_dur{duration_s:.2f}s"
        plot_unified_trial_qc(
            all_crossings, features, targets, fs, BIN_MS, epoch, i,
            session_qc_dir / f"{tag}_unified.png",
        )
        save_trial_wav(audio, fs, epoch, session_qc_dir / f"{tag}.wav")

    print(f"  Saved {min(n_qc_trials, len(epochs))} unified trial QC figures to {session_qc_dir}")

    return features, targets


# ---------------------------------------------------------------------------
# Main -- walk sessions for exactly one (subject, region, date), concatenate
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description=__doc__)
    add_identity_args(parser)
    parser.add_argument(
        "--raw-base-dir", required=True,
        help="Directory containing one subfolder per date (e.g. "
             "'.../aSTG' if your .ns5 files live at '.../aSTG/07_19_11/*.ns5')",
    )
    parser.add_argument(
        "--n-qc-trials", type=int, default=5,
        help="Number of candidate speech epochs to render unified QC figures for",
    )
    args = parser.parse_args()

    paths = PipelinePaths.from_args(args)
    print(f"Processing {paths.label()}")

    date_dir = Path(args.raw_base_dir) / args.date
    if not date_dir.is_dir():
        raise FileNotFoundError(f"No such date directory: {date_dir}")

    sessions = sorted(date_dir.glob("*.ns5"))
    if not sessions:
        raise FileNotFoundError(f"No .ns5 files found in {date_dir}")

    all_features, all_targets = [], []
    for session_path in sessions:
        session_tag = f"{args.date}_{session_path.stem}"
        print(f"\nProcessing {session_tag}...")
        try:
            features, targets = process_session(session_path, paths, session_tag, args.n_qc_trials)
            all_features.append(features)
            all_targets.append(targets)
        except Exception as e:
            print(f"  FAILED on {session_tag}: {e}")

    if not all_features:
        print("No sessions processed successfully -- nothing to concatenate.")
        return

    features_full = np.concatenate(all_features, axis=0)
    targets_full = np.concatenate(all_targets, axis=0)

    np.save(paths.pipeline / "features.npy", features_full)
    np.save(paths.pipeline / "targets.npy", targets_full)

    print(f"\nFinal features.npy: {features_full.shape}")
    print(f"Final targets.npy:  {targets_full.shape}")
    print(f"Saved to {paths.pipeline}/features.npy and targets.npy")
    print(f"Unified QC figures under {paths.qc}/<session>/")


if __name__ == "__main__":
    main()
