"""
generate_results_table.py

Reads pipeline_data/aggregate/analysis/all_dates_all_decoders_metrics.csv
(produced by `analyze_results.py --mode aggregate`) and writes a
ready-to-\\input booktabs LaTeX table summarizing mean +/- std correlation
per decoder across every processed date -- so the numbers in the report
are always exactly correct and regenerate automatically as more dates are
added, rather than being hand-transcribed off a chart.

Usage:
    python3 generate_results_table.py \
        --csv pipeline_data/aggregate/analysis/all_dates_all_decoders_metrics.csv \
        --out figures/results_table.tex
"""

import argparse
import pandas as pd
from pipeline_paths import DEFAULT_DATA_ROOT  # noqa: E402  (paths.yaml)

DECODER_DISPLAY_NAMES = {
    "kalman_filter": "Kalman Filter",
    "wiener_filter": "Wiener Filter",
    "wiener_cascade": "Wiener Cascade",
    "dense_nn": "Dense NN",
    "simple_rnn": "Simple RNN",
    "gru_rnn": "GRU RNN",
    "lstm_rnn": "LSTM RNN",
    "lsnn": "LSNN (spiking)",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", default=DEFAULT_DATA_ROOT + "/aggregate/analysis/all_dates_all_decoders_metrics.csv")
    parser.add_argument("--out", default="figures/results_table.tex")
    args = parser.parse_args()

    df = pd.read_csv(args.csv)
    n_dates = df["run_label"].nunique()

    summary = (
        df.groupby("decoder")[["train_mean_rho", "valid_mean_rho", "test_mean_rho"]]
        .agg(["mean", "std"])
        .sort_values(("valid_mean_rho", "mean"), ascending=False)
    )

    lines = []
    lines.append(r"% Auto-generated by generate_results_table.py -- do not edit by hand.")
    lines.append(r"\begin{table}[ht]")
    lines.append(r"\centering")
    lines.append(r"\begin{tabular}{lccc}")
    lines.append(r"\toprule")
    lines.append(r"Decoder & Train $\bar{\rho} \pm \sigma$ & Valid $\bar{\rho} \pm \sigma$ & Test $\bar{\rho} \pm \sigma$ \\")
    lines.append(r"\midrule")

    for decoder, row in summary.iterrows():
        name = DECODER_DISPLAY_NAMES.get(decoder, decoder)
        tr_m, tr_s = row[("train_mean_rho", "mean")], row[("train_mean_rho", "std")]
        va_m, va_s = row[("valid_mean_rho", "mean")], row[("valid_mean_rho", "std")]
        te_m, te_s = row[("test_mean_rho", "mean")], row[("test_mean_rho", "std")]
        lines.append(
            f"{name} & {tr_m:.2f} $\\pm$ {tr_s:.2f} & {va_m:.2f} $\\pm$ {va_s:.2f} & "
            f"{te_m:.2f} $\\pm$ {te_s:.2f} \\\\"
        )

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(
        rf"\caption{{Mean $\pm$ standard deviation of Pearson correlation ($\rho$) between "
        rf"target and predicted mel-spectrogram bands, across {n_dates} recording days "
        rf"(Neil, aSTG), sorted by mean validation correlation.}}"
    )
    lines.append(r"\label{tab:cross_date_summary}")
    lines.append(r"\end{table}")

    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Wrote {args.out} ({n_dates} dates, {len(summary)} decoders)")
    print(summary.round(3))


if __name__ == "__main__":
    main()